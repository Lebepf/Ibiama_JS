// Definindo um objeto chamado 'cachorro'
let cachorro = {
    // Dentro do objeto, temos uma propriedade chamada 'latir' que é uma função
    latir: function() {
        // A função 'latir' imprime "Au Au" no console quando chamada
        console.log("Au Au");
    }
}

// Aqui estamos chamando a função 'latir' do objeto 'cachorro', o que vai imprimir "Au Au" no console
cachorro.latir();
